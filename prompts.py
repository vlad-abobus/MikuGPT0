def _emotion_list_for_prompt(emotion_set: str) -> str:
    labels = emotion_labels_for_set(emotion_set)
    descs = emotion_descs_for_set(emotion_set)
    lines = []
    for key in emotion_keys_for_set(emotion_set):
        lbl = labels.get(key, key)
        desc = descs.get(key, "")
        if desc:
            lines.append(f'"{key}" — {lbl} ({desc})')
        else:
            lines.append(f'"{key}" — {lbl}')
    return "\n".join(lines)


