def _emotion_list_for_prompt(emotion_set: str, compact: bool = False) -> str:
    labels = emotion_labels_for_set(emotion_set)
    descs = emotion_descs_for_set(emotion_set)
    lines = []
    for key in emotion_keys_for_set(emotion_set):
        if compact:
            lines.append(f"  • {key} — {labels.get(key, key)}")
        else:
            hint = descs.get(key) or labels.get(key, key)
            lines.append(f"  • {key} — {labels.get(key, key)}: {hint}")
    return "\n".join(lines)


